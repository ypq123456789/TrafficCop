#!/bin/bash

# ============================================================
# 日志轮转与读取（共享函数库）
# ------------------------------------------------------------
# 由 tg_notifier.sh / pushplus_notifier.sh / serverchan_notifier.sh
# 三个通知脚本共同 source。
#
# 为什么不直接抄在各自脚本里：这三处逻辑必须完全一致，
# 复制三份的话以后改一处漏两处，是典型的埋雷做法。
#
# 依赖：调用方必须先定义 $LOG_FILE。
# ============================================================

# 单文件上限与保留份数。
# 与主脚本 trafficcop.sh 保持一致 —— 轮转动作实际由主脚本在每次 --run
# 时执行，这里只是读侧，数值不同步会导致「归档文件读不到」或
# 「读了一堆早就该删掉的旧归档」，所以两边必须一致。
LOG_MAX_BYTES=${LOG_MAX_BYTES:-$((10 * 1024 * 1024))}   # 10MB
LOG_KEEP=${LOG_KEEP:-3}                                 # 保留 3 份归档

# 每次读取时在文件尾部的扫描窗口（字节）。
# 「最近一条」几乎总在尾部，没必要把整个文件倒读进内存。
LOG_WINDOW_BYTES=${LOG_WINDOW_BYTES:-2097152}           # 2MB

# 【读】取最近一条匹配行。
#
# 替代原来的裸 `tac "$LOG_FILE" | grep -m 1 -E "$pattern"`，两点改进：
#   1. 按「当前文件 -> .1 -> .2 ...」顺序查，所以日志轮转之后
#      仍然能找到近期记录（裸 tac 只看当前文件，轮转后目标行被
#      推进归档里，就会「查不到」——而下游限速/解限判断依赖这个结果）。
#   2. 只在文件尾部窗口内查找，不把整文件倒读进内存。
#      原写法在 150MB 的日志上每分钟全扫一次，越跑越慢。
#
# 注意窗口截断的边界：tail -c N 在 N 小于文件大小时，可能把首行截成半行。
# 半行文本不会匹配到完整模式（无害），但也可能恰好匹配到模式片段。
# 因此【仅在确实发生截断时】丢弃窗口内的第一行；
# 若文件本身就比窗口小（tail -c 返回的是完整文件），则一个字都不能丢 ——
# 早期版本无条件 `tail -n +2`，导致只有一行的文件被整个读空，
# 归档里的记录明明存在却查不到，属于功能退化。
#
# 命中：输出该行并返回 0；未命中：不输出，返回 1。
#
# ------------------------------------------------------------
# 为什么「当前文件」和「归档文件」要用不同策略（此处曾出过一个真 bug）
# ------------------------------------------------------------
# 初版对所有文件统一用「尾部窗口」，结果：一条限速记录被轮转推进 .1
# 之后，若它位于 .1 的开头，就会被窗口切掉、永远查不到 ——
# 而下游的状态判断（当前是限速 / 已解限 / 新周期）正是依赖这条记录。
# 实测：12MB 归档，记录在第 1 行，查不到。
#
# 正确的划分依据是「文件会不会继续增长」：
#   - 当前文件：正在被 tee 追加，「最近一条」几乎总在尾部。
#     用窗口扫描，避免在 100MB+ 的文件上每分钟全量倒读。
#   - 归档文件：已冻结、不再增长，且最多 LOG_KEEP 份（默认 3×10MB）。
#     「最近一条」可能落在任何位置，必须全量反向扫描才不漏。
#     代价可控：只在当前文件没命中时才会走到这里，且总量有上限。
log_recent_match() {
    local pattern="$1"
    local f hit size

    for f in "$LOG_FILE" "${LOG_FILE}.1" "${LOG_FILE}.2" \
             "${LOG_FILE}.3" "${LOG_FILE}.4" "${LOG_FILE}.5"; do
        [ -f "$f" ] || continue

        if [ "$f" = "$LOG_FILE" ]; then
            # ---- 会继续增长的文件：只扫尾部窗口 ----
            size=$(stat -c %s "$f" 2>/dev/null || stat -f %z "$f" 2>/dev/null || echo 0)
            case "$size" in ''|*[!0-9]*) size=0 ;; esac

            if [ "$size" -gt "$LOG_WINDOW_BYTES" ]; then
                # 发生了截断：首行可能是半行，丢掉
                hit=$(tail -c "$LOG_WINDOW_BYTES" "$f" 2>/dev/null \
                      | tail -n +2 2>/dev/null \
                      | tac 2>/dev/null \
                      | grep -m 1 -E "$pattern")
            else
                # 完整文件：一行都不丢
                hit=$(tac "$f" 2>/dev/null | grep -m 1 -E "$pattern")
            fi
        else
            # ---- 已冻结的归档：必须全量反向扫描，不能用窗口 ----
            hit=$(tac "$f" 2>/dev/null | grep -m 1 -E "$pattern")
        fi

        if [ -n "$hit" ]; then
            printf '%s\n' "$hit"
            return 0
        fi
    done
    return 1
}

# ============================================================
# 新周期事件（issue #25）
# ------------------------------------------------------------
# 新周期是「事件」，不是「状态」，所以不能靠日志判断：
# 主脚本在重置的那一次运行里会连着写两行 —— 先「新的流量周期开始，重置限制」，
# 紧接着「流量正常，清除所有限制」。通知脚本每分钟才轮询一次，
# log_recent_match 只返回最新一条匹配行，看到的基本总是后者。
# 换句话说，靠日志判断等于用 1 秒的窗口去撞 60 秒的轮询，
# 正常用户几乎永远收不到这条通知（旧版本收到的 485 条重复，是「取数一直失败
# 导致新周期那行始终是最新一条」的病态结果）。
#
# 现在改读主脚本落盘的周期标识：trafficcop.sh 每次 --run 都会把当前周期起点
# 写进 .last_period_reset；通知侧各自记一份「已推送过的周期起点」，
# 两者不同才推。与日志时序完全解耦。
# ============================================================

# 主脚本写的周期标识（当前周期起点）
new_cycle_state_path() {
    printf '%s\n' "${NEW_CYCLE_STATE_FILE:-${WORK_DIR:-.}/.last_period_reset}"
}

# 本通知脚本记的「已推送过的周期起点」
new_cycle_mark_path() {
    printf '%s\n' "${NEW_CYCLE_MARK_FILE:-${WORK_DIR:-.}/.last_new_cycle_notified}"
}

# 返回 0 = 本周期还没推送过（该推），并把「待通知的周期」打到 stdout；
# 返回 1 = 无需推送（stdout 为空）。
# 调用方必须把 stdout 原样交给 new_cycle_notify_mark：
# 发送期间主脚本可能又推进了周期，重新读一次会把新周期记成「已通知」却没发。
#
# 首次运行（没有标记文件）只静默登记当前周期、不补推 ——
# 否则每台机器升级完都会凭空多一条「新周期」。
new_cycle_notify_pending() {
    local cur last sf mf
    sf=$(new_cycle_state_path)
    mf=$(new_cycle_mark_path)

    cur=$(head -n 1 "$sf" 2>/dev/null | tr -d '[:space:]')
    [ -n "$cur" ] || return 1

    last=$(head -n 1 "$mf" 2>/dev/null | tr -d '[:space:]')
    if [ -z "$last" ]; then
        printf '%s\n' "$cur" > "$mf" 2>/dev/null
        return 1
    fi

    [ "$cur" != "$last" ] || return 1
    printf '%s\n' "$cur"
}

# 记录「本周期已通知」。只在【发送成功】后调用，参数就是 pending 打出来的周期。
# 发送失败就别调，标记留着不改，下一分钟自然会重试，不会把通知永久丢掉。
new_cycle_notify_mark() {
    local period="$1" mf
    [ -n "$period" ] || return 1
    mf=$(new_cycle_mark_path)
    printf '%s\n' "$period" > "$mf" 2>/dev/null
    return 0
}
